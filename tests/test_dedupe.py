"""
Tests for duplicate handling (v3.1.1, Phase 0.6).

Duplicate responses are real respondents. Keeping them is what makes counts,
prevalence, and agreement statistics mean what they say. These tests pin that
they survive the pipeline, that the optional embedding-dedupe optimization
produces the same vectors it would have without it, and that a duplicate id
column — the join key for agreement and the project store — gets flagged.
"""

from __future__ import annotations

import logging
import sys
from pathlib import Path
from unittest.mock import MagicMock, patch

import numpy as np
import pandas as pd
import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from analyze_survey import build_embeddings, count_unique_texts, prepare_dataset


def _config(**prep):
    base = {"min_chars": 3, "drop_duplicates": False, "max_rows": None}
    base.update(prep)
    return {
        "input": {"text_column": "text", "question_column": "q", "id_column": "rid"},
        "preprocessing": base,
    }


class TestCountUniqueTexts:
    def test_counts_total_and_unique(self):
        assert count_unique_texts(["a", "a", "b"]) == (3, 2)

    def test_all_unique(self):
        assert count_unique_texts(["a", "b", "c"]) == (3, 3)

    def test_empty(self):
        assert count_unique_texts([]) == (0, 0)


class TestDuplicatesAreKept:
    def test_duplicate_responses_survive_by_default(self):
        """If 3 people all say "cost", that is the finding — not one row."""
        df = pd.DataFrame(
            {
                "text": ["cost", "cost", "cost", "parking"],
                "q": ["Q1"] * 4,
                "rid": ["1", "2", "3", "4"],
            }
        )
        out = prepare_dataset(df, _config())
        assert len(out) == 4
        assert (out["response_text"] == "cost").sum() == 3

    def test_opt_in_dedup_still_available(self):
        df = pd.DataFrame(
            {"text": ["cost", "cost"], "q": ["Q1", "Q1"], "rid": ["1", "2"]}
        )
        out = prepare_dataset(df, _config(drop_duplicates=True))
        assert len(out) == 1

    def test_same_text_different_questions_kept_even_when_deduping(self):
        """"None" under two questions is two different answers."""
        df = pd.DataFrame(
            {"text": ["None", "None"], "q": ["Q1", "Q2"], "rid": ["1", "2"]}
        )
        out = prepare_dataset(df, _config(drop_duplicates=True))
        assert len(out) == 2


class TestDuplicateIdWarning:
    def test_duplicate_ids_warn(self, caplog):
        df = pd.DataFrame(
            {"text": ["aaa", "bbb"], "q": ["Q1", "Q1"], "rid": ["dup", "dup"]}
        )
        with caplog.at_level(logging.WARNING, logger="survey_nlp"):
            prepare_dataset(df, _config())
        assert any("duplicate" in r.message.lower() for r in caplog.records)

    def test_unique_ids_do_not_warn(self, caplog):
        df = pd.DataFrame(
            {"text": ["aaa", "bbb"], "q": ["Q1", "Q1"], "rid": ["1", "2"]}
        )
        with caplog.at_level(logging.WARNING, logger="survey_nlp"):
            prepare_dataset(df, _config())
        assert not any("duplicate" in r.message.lower() for r in caplog.records)

    def test_autogenerated_ids_never_warn(self, caplog):
        """Positional ids are unique by construction."""
        df = pd.DataFrame({"text": ["aaa", "aaa"], "q": ["Q1", "Q1"]})
        cfg = _config()
        cfg["input"]["id_column"] = None
        with caplog.at_level(logging.WARNING, logger="survey_nlp"):
            out = prepare_dataset(df, cfg)
        assert out["response_id"].nunique() == 2
        assert not any("duplicate" in r.message.lower() for r in caplog.records)


class TestEmbeddingDedupe:
    """The optimization must be invisible in the output — that's the deal."""

    def _encoder(self):
        """A stand-in model: one deterministic vector per distinct text."""
        vectors = {"a": [1.0, 0.0], "b": [0.0, 1.0], "c": [0.5, 0.5]}

        def encode(texts, **kwargs):
            return np.array([vectors[t] for t in texts], dtype=np.float32)

        model = MagicMock()
        model.encode.side_effect = encode
        return model

    def test_dedupe_returns_one_row_per_input(self):
        model = self._encoder()
        with patch("analyze_survey.SentenceTransformer", return_value=model):
            out = build_embeddings(["a", "a", "b"], "m", 32, True, dedupe=True)
        assert out.shape == (3, 2)

    def test_dedupe_broadcasts_vectors_to_the_right_rows(self):
        model = self._encoder()
        with patch("analyze_survey.SentenceTransformer", return_value=model):
            out = build_embeddings(["a", "b", "a"], "m", 32, True, dedupe=True)
        np.testing.assert_array_equal(out[0], out[2])
        assert not np.array_equal(out[0], out[1])

    def test_dedupe_matches_the_undeduped_result(self):
        texts = ["a", "b", "a", "c", "b", "a"]
        with patch("analyze_survey.SentenceTransformer", return_value=self._encoder()):
            plain = build_embeddings(texts, "m", 32, True, dedupe=False)
        with patch("analyze_survey.SentenceTransformer", return_value=self._encoder()):
            deduped = build_embeddings(texts, "m", 32, True, dedupe=True)
        np.testing.assert_array_equal(plain, deduped)

    def test_dedupe_only_encodes_distinct_texts(self):
        """The point of the flag: 6 rows, 3 encoder inputs."""
        model = self._encoder()
        with patch("analyze_survey.SentenceTransformer", return_value=model):
            build_embeddings(["a", "b", "a", "c", "b", "a"], "m", 32, True, dedupe=True)
        encoded = model.encode.call_args[0][0]
        assert encoded == ["a", "b", "c"]

    def test_default_encodes_every_row(self):
        """Off by default — reproducibility beats speed unless asked."""
        model = self._encoder()
        with patch("analyze_survey.SentenceTransformer", return_value=model):
            build_embeddings(["a", "a", "b"], "m", 32, True)
        assert model.encode.call_args[0][0] == ["a", "a", "b"]

    def test_dedupe_preserves_first_seen_order(self):
        model = self._encoder()
        with patch("analyze_survey.SentenceTransformer", return_value=model):
            build_embeddings(["c", "a", "b"], "m", 32, True, dedupe=True)
        assert model.encode.call_args[0][0] == ["c", "a", "b"]

    def test_all_duplicates_collapse_to_one_encode(self):
        model = self._encoder()
        with patch("analyze_survey.SentenceTransformer", return_value=model):
            out = build_embeddings(["a"] * 20, "m", 32, True, dedupe=True)
        assert model.encode.call_args[0][0] == ["a"]
        assert out.shape == (20, 2)
